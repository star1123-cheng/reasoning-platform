/** 判定：轉小寫、空白正規化後，包含任一關鍵詞即判對 */
export const isCorrect = (c: Case, input: string): boolean => {
  const a = input.toLowerCase().replace(/\s+/g, ' ').trim();
  return !!a && c.k.some((k) => a.includes(k));
};
